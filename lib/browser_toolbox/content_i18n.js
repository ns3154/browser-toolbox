  const supportedLocales = Object.freeze(Object.keys(catalogs));
  let requestedLocale = null;

  function normalizeLocale(value) {
    const parts = String(value).toLowerCase().replaceAll("_", "-").split("-");
    const language = parts[0];
    if (language === "zh") {
      // 显式文字体系优先于地区；港澳和台湾在未指定文字体系时使用繁体中文。
      if (parts.includes("hant")) return "zh_TW";
      if (parts.includes("hans")) return "zh_CN";
      return parts.some((part) => ["tw", "hk", "mo"].includes(part)) ? "zh_TW" : "zh_CN";
    }
    return Object.hasOwn(catalogs, language) ? language : "en";
  }

  function chromeMessage(key, substitutions) {
    try {
      if (globalThis.chrome?.i18n?.getMessage) {
        const message = chrome.i18n.getMessage(key, substitutions);
        if (message) return message;
      }
    } catch (_) {
      // 测试桩可能没有 i18n API，回退到内置英文值。
    }
    return catalogs.en[key] || key;
  }

  function locale() {
    if (requestedLocale) return requestedLocale;
    try {
      return normalizeLocale(chrome.i18n.getUILanguage?.() || navigator.language || "en");
    } catch (_) {
      return normalizeLocale(navigator.language || "en");
    }
  }

  function message(key, substitutions) {
    const catalog = catalogs[locale()] || catalogs.en;
    return catalog[key] || chromeMessage(key, substitutions);
  }

  function hasMessage(key) {
    if (Object.hasOwn(catalogs.en, key) || Object.hasOwn(catalogs.zh_CN, key)) return true;
    try {
      return Boolean(chrome.i18n?.getMessage?.(key));
    } catch (_) {
      return false;
    }
  }

  function setLocale(value) {
    requestedLocale = value === "auto" || !value ? null : normalizeLocale(value);
    return locale();
  }

  globalThis.BrowserToolboxI18n = Object.freeze({
    message,
    hasMessage,
    locale,
    setLocale,
    supportedLocales,
  });
